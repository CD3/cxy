"""Generate conanfile.py and read Conan's dependency metadata."""

import json
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from cxy.core import conditions
from cxy.core.errors import CxyError
from cxy.core.manifest import Dependency, Manifest, OptionValue

_STANDALONE_IMPORTS = [
    "from conan.tools.build import check_min_cppstd",
    "from conan.tools.cmake import CMake, cmake_layout",
]


@dataclass(frozen=True)
class CMakeInfo:
    """How to use a Conan package from CMake."""

    package: str
    target: str
    components: frozenset[str] = frozenset()
    """The targets of its components."""


def conanfile(manifest: Manifest, *, standalone: bool = False, shared: bool | None = None) -> str:
    """Return the conanfile.py text.

    A ``standalone`` recipe is for use without cxy, so it carries what cxy would otherwise
    pass on the command line. Unless ``shared`` is None, it also has a ``shared`` option with
    that default, for those who build it with Conan.
    """
    conditional = [c for c in manifest.when if c.dependencies or c.dev_dependencies]
    dependencies = (
        *manifest.dependencies,
        *manifest.dev_dependencies,
        # Conan ignores the options of packages that are not needed.
        *(d for c in conditional for d in (*c.dependencies, *c.dev_dependencies)),
    )
    offered = standalone and shared is not None
    options: dict[str, OptionValue] = {"shared": bool(shared)} if offered else {}
    options |= {
        f"{dependency.name}/*:{key}": value
        for dependency in dependencies
        for key, value in dependency.options.items()
    }
    lines = [
        *([] if standalone else ["# Generated by cxy. Do not edit."]),
        "from conan import ConanFile",
        *(_STANDALONE_IMPORTS if standalone else []),
        "",
        "",
        "class Project(ConanFile):",
        f"    name = {manifest.name!r}",
        f"    version = {manifest.version!r}",
        '    settings = "os", "compiler", "build_type", "arch"',
        '    generators = "CMakeDeps", "CMakeToolchain"',
    ]
    if offered:
        lines.append('    options = {"shared": [True, False]}')
    if options:
        lines.append("    default_options = {")
        lines += [f"        {key!r}: {value!r}," for key, value in options.items()]
        lines.append("    }")
    requires = _requires("requires", manifest.dependencies)
    for c in conditional:
        if c.dependencies:
            requires += [f"        if {conditions.python(c.condition)}:"]
            requires += [f"    {line}" for line in _requires("requires", c.dependencies)]
    for name, version in manifest.overrides.items():
        requires.append(f"        self.requires({f'{name}/{version}'!r}, override=True)")
    if requires:
        lines += ["", "    def requirements(self):", *requires]
    test_requires = _requires("test_requires", manifest.dev_dependencies)
    for c in conditional:
        if c.dev_dependencies:
            test_requires += [f"        if {conditions.python(c.condition)}:"]
            test_requires += [
                f"    {line}" for line in _requires("test_requires", c.dev_dependencies)
            ]
    if test_requires:
        lines += ["", "    def build_requirements(self):", *test_requires]
    if standalone:
        lines += [
            "",
            "    def validate(self):",
            f'        check_min_cppstd(self, "{manifest.std}")',
            "",
            "    def layout(self):",
            f"        cmake_layout(self, build_folder={manifest.layout.build!r})"
            if manifest.layout.build != "build"
            else "        cmake_layout(self)",
            "",
            "    def build(self):",
            "        cmake = CMake(self)",
            "        cmake.configure()",
            "        cmake.build()",
        ]
    return "\n".join(lines) + "\n"


def _requires(method: str, dependencies: tuple[Dependency, ...]) -> list[str]:
    return [
        f"        self.{method}({d.ref!r}{', force=True' if d.force else ''})" for d in dependencies
    ]


def read_graph(output: str) -> dict[str, CMakeInfo]:
    """Extract CMake names from ``conan install --format=json`` output."""
    try:
        nodes = json.loads(output)["graph"]["nodes"]
    except (ValueError, KeyError, TypeError) as error:
        raise CxyError("could not understand Conan's JSON output") from error
    result: dict[str, CMakeInfo] = {}
    for node in nodes.values():
        if node.get("context") != "host" or not node.get("cpp_info"):
            continue
        name = node["name"]
        cpp_info: Mapping[str, Any] = node["cpp_info"]
        root = _properties(cpp_info, "root")
        result[name] = CMakeInfo(
            package=root.get("cmake_file_name", name),
            target=root.get("cmake_target_name", f"{name}::{name}"),
            components=frozenset(
                target
                for key in cpp_info
                if key != "root" and (target := _properties(cpp_info, key).get("cmake_target_name"))
            ),
        )
    return result


def resolve(dependency: Dependency, graph: Mapping[str, CMakeInfo]) -> CMakeInfo:
    info = graph.get(
        dependency.name, CMakeInfo(dependency.name, f"{dependency.name}::{dependency.name}")
    )
    return CMakeInfo(dependency.cmake_package or info.package, info.target, info.components)


def _properties(cpp_info: Mapping[str, Any], component: str) -> Mapping[str, Any]:
    return (cpp_info.get(component) or {}).get("properties") or {}
