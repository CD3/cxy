"""Generate CMakeLists.txt."""

import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass

from cxy.core import conan
from cxy.core.conan import CMakeInfo
from cxy.core.errors import CxyError
from cxy.core.manifest import Dependency, Manifest
from cxy.core.project import Sources

MINIMUM_VERSION = "3.24"
CATCH2 = "catch2"


@dataclass(frozen=True)
class TestProgram:
    __test__ = False  # Not a pytest class.

    target: str
    sources: tuple[str, ...]
    is_unit: bool

    @property
    def isolated_target(self) -> str:
        return f"{self.target}_isolated"


def test_programs(manifest: Manifest, sources: Sources) -> list[TestProgram]:
    name = manifest.name
    used = {name, f"{name}_lib", f"{name}_app", f"{name}_tests", *sources.unit_tests}
    programs = []
    for source in sources.unit_tests:
        stem = re.sub(r"[^A-Za-z0-9_]", "_", source.rpartition(".")[0])
        base = target = f"{name}_{stem}"
        number = 2
        while target in used:
            target = f"{base}_{number}"
            number += 1
        used |= {target, f"{target}_isolated"}
        programs.append(TestProgram(target, (source,), True))
    if sources.tests:
        programs.append(TestProgram(f"{name}_tests", sources.tests, False))
    return programs


def cmakelists(
    manifest: Manifest,
    sources: Sources,
    graph: Mapping[str, CMakeInfo],
    *,
    root: str | None = None,
    isolated: Mapping[str, Sequence[str]] | None = None,
) -> str:
    """Return the CMakeLists.txt text.

    ``root`` is the project root relative to the generated file, or None if the file goes
    in the project root. ``isolated`` maps unit tests to the only project sources to compile
    for them; those tests get an additional, isolated program.
    """
    layout = manifest.layout
    if not sources.has_library and sources.main is None:
        raise CxyError("nothing to build: no library sources, public headers or main file found")
    if sources.app and sources.main is None:
        raise CxyError(f"{layout.src}/ contains sources but no main.cpp")

    lib = f"{manifest.name}_lib"
    app = f"{manifest.name}_app"
    exe = manifest.name
    standard = f"cxx_std_{manifest.std}"

    def path(relative: str) -> str:
        return quote(relative) if root is None else '"${ROOT_DIR}/' + quote(relative)[1:]

    include_dir, lib_dir, src_dir = map(path, (layout.include, layout.lib, layout.src))
    dependency_targets = _targets(manifest.dependencies, graph)

    out = [
        *([] if root is None else ["# Generated by cxy. Do not edit."]),
        f"cmake_minimum_required(VERSION {MINIMUM_VERSION})",
        f"project({manifest.name} LANGUAGES CXX)",
        "",
        "include(CTest)",
    ]
    if root is not None:
        out.append(f"get_filename_component(ROOT_DIR {quote(root)} ABSOLUTE)")
    out += [
        "",
        "if(NOT CMAKE_CXX_STANDARD)",
        f"  set(CMAKE_CXX_STANDARD {manifest.std})",
        "endif()",
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
        "set(CMAKE_CXX_EXTENSIONS OFF)",
        'set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/bin")',
        "",
    ]
    out += _find_packages(manifest.dependencies, graph)

    # What the application and tests build on: the library, or the dependencies themselves.
    base = dependency_targets
    if sources.has_library:
        base = [lib]
        if sources.lib:
            out += _call("add_library", [lib, "STATIC"], map(path, sources.lib))
            out += _call("set_target_properties", [lib, "PROPERTIES", "OUTPUT_NAME", manifest.name])
            out += _call("target_include_directories", [lib, "PUBLIC", include_dir])
            out += _call("target_include_directories", [lib, "PRIVATE", lib_dir])
            scope = "PUBLIC"
        else:
            out += _call("add_library", [lib, "INTERFACE"])
            out += _call("target_include_directories", [lib, "INTERFACE", include_dir])
            scope = "INTERFACE"
        out += _call("target_compile_features", [lib, scope, standard])
        out += _link(lib, scope, dependency_targets)
        out.append("")

    app_links = base
    if sources.main is not None:
        if sources.app:
            # An object library lets the tests link the application's code without main().
            out += _call("add_library", [app, "OBJECT"], map(path, sources.app))
            out += _call("target_include_directories", [app, "PUBLIC", src_dir])
            out += _call("target_compile_features", [app, "PUBLIC", standard])
            out += _link(app, "PUBLIC", base)
            app_links = [app, *base]
        out += _call("add_executable", [exe], [path(sources.main)])
        out += _call("target_include_directories", [exe, "PRIVATE", src_dir])
        out += _call("target_compile_features", [exe, "PRIVATE", standard])
        out += _link(exe, "PRIVATE", app_links)
        out.append("")

    if programs := test_programs(manifest, sources):
        others = [d for d in manifest.dev_dependencies if d.name != CATCH2]
        test_links = [*_targets(others, graph), *_catch2_main(manifest, graph)]
        body = [*_find_packages(manifest.dev_dependencies, graph), "include(Catch)"]
        for program in programs:
            target = program.target
            body += ["", *_call("add_executable", [target], map(path, program.sources))]
            body += _call("target_include_directories", [target, "PRIVATE", lib_dir, src_dir])
            body += _call("target_compile_features", [target, "PRIVATE", standard])
            body += _link(target, "PRIVATE", [*app_links, *test_links])
            # Different programs may contain tests with the same name.
            body.append(
                f'catch_discover_tests({target} DISCOVERY_MODE PRE_TEST TEST_PREFIX "{target}:")'
            )
        for program in programs:
            needed = (isolated or {}).get(program.sources[0]) if program.is_unit else None
            if needed is None:
                continue
            target = program.isolated_target
            files = [*program.sources, *needed]
            body += [
                "",
                *_call("add_executable", [target, "EXCLUDE_FROM_ALL"], map(path, files)),
            ]
            body += _call(
                "target_include_directories", [target, "PRIVATE", include_dir, lib_dir, src_dir]
            )
            body += _call("target_compile_features", [target, "PRIVATE", standard])
            body += _link(target, "PRIVATE", [*dependency_targets, *test_links])
        out += ["if(BUILD_TESTING)", *(f"  {line}" if line else "" for line in body), "endif()"]
    return "\n".join(out).rstrip() + "\n"


def quote(value: str) -> str:
    """Quote a CMake argument, disabling variable expansion."""
    for char in ("\\", '"', "$"):
        value = value.replace(char, f"\\{char}")
    return f'"{value}"'


def _call(command: str, arguments: Iterable[str], items: Iterable[str] = ()) -> list[str]:
    head = f"{command}({' '.join(arguments)}"
    items = list(items)
    if not items:
        return [f"{head})"]
    return [head, *(f"  {item}" for item in items), ")"]


def _link(target: str, scope: str, libraries: Iterable[str]) -> list[str]:
    libraries = list(libraries)
    return _call("target_link_libraries", [target, scope, *libraries]) if libraries else []


def _find_packages(dependencies: Iterable[Dependency], graph: Mapping[str, CMakeInfo]) -> list[str]:
    packages = dict.fromkeys(conan.resolve(d, graph).package for d in dependencies)
    return [f"find_package({package} REQUIRED CONFIG)" for package in packages]


def _targets(dependencies: Iterable[Dependency], graph: Mapping[str, CMakeInfo]) -> list[str]:
    targets: list[str] = []
    for dependency in dependencies:
        targets += dependency.cmake_targets or (conan.resolve(dependency, graph).target,)
    return targets


def _catch2_main(manifest: Manifest, graph: Mapping[str, CMakeInfo]) -> tuple[str, ...]:
    for dependency in manifest.dev_dependencies:
        if dependency.name == CATCH2:
            return dependency.cmake_targets or ("Catch2::Catch2WithMain",)
    raise CxyError(
        "tests need a test framework: add catch2 (3.x) to [dev-dependencies] in cxy.toml"
    )
