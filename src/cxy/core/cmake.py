"""Generate CMakeLists.txt."""

import re
from collections.abc import Callable, Iterable, Mapping, Sequence
from pathlib import Path

from cxy.core import conan, conditions, frameworks
from cxy.core.conan import CMakeInfo
from cxy.core.conditions import Condition
from cxy.core.errors import CxyError
from cxy.core.manifest import Component, Conditional, Dependency, Kind, Manifest, Settings
from cxy.core.project import Sources
from cxy.core.testing import TestProgram

MINIMUM_VERSION = "3.24"

_Body = Callable[[Condition | None], list[str]]
"""Lines to write, given the condition to put in generator expressions, if any."""

# The sources are outside the directory of the generated file, so CMake puts their full path
# in the names of object files. On Windows that can make them too long for the compiler.
_SHORT_PATHS = [
    "if(CMAKE_HOST_WIN32)",
    '  set(CMAKE_INTERMEDIATE_DIR_STRATEGY SHORT CACHE STRING "")  # CMake 4.2',
    "endif()",
]


def cmakelists(
    manifest: Manifest,
    sources: Sources,
    graph: Mapping[str, CMakeInfo],
    *,
    programs: Sequence[TestProgram] = (),
    root: str | None = None,
    isolated: Mapping[str, Sequence[str]] | None = None,
) -> str:
    """Return the CMakeLists.txt text.

    ``root`` is the project root relative to the generated file, or None if the file goes
    in the project root. ``isolated`` maps unit tests to the only project sources to compile
    for them; those tests get an additional, isolated program.
    """
    # The sources may have been found for the manifest before its conditions were resolved.
    sources = sources.described_by(manifest)
    libraries, executables = sources.libraries, sources.programs
    if not libraries and not executables:
        raise CxyError("nothing to build: no library sources, public headers or main file found")
    named = {*manifest.libraries, *manifest.programs}
    for found in sources.components:
        component = found.component
        if component.kind is Kind.PROGRAM and found.sources and found.main is None:
            raise CxyError(f"{component.directory}/ contains sources but no main.cpp")
        if component in named and not found.exists:
            if component.kind is Kind.LIBRARY:
                missing = f"no sources or headers in {component.directory}/"
            else:
                missing = f"no {component.main}" + (
                    "" if Path(component.main or "").suffix else ".cpp"
                )
            raise CxyError(f"{component.where}: {missing}")
    # Whether those who build the exported project choose the kind of library.
    shared = shared_default(sources) if root is None else None

    standard = f"cxx_std_{manifest.std}"

    def path(relative: str) -> str:
        return quote(relative) if root is None else '"${ROOT_DIR}/' + quote(relative)[1:]

    dependency_targets = _targets(manifest.dependencies, graph)
    library_targets = {found.component.name: found.component.target for found in libraries}

    def links(component: Component) -> list[str]:
        """What a component builds on: the libraries it uses, or the dependencies themselves."""
        used = [library_targets[name] for name in component.uses if name in library_targets]
        return used or dependency_targets

    out = [
        *([] if root is None else ["# Generated by cxy. Do not edit."]),
        f"cmake_minimum_required(VERSION {MINIMUM_VERSION})",
        *([] if root is None else _SHORT_PATHS),
        f"project({manifest.name} LANGUAGES CXX)",
        "",
        "include(CTest)",
    ]
    if root is not None:
        out.append(f"get_filename_component(ROOT_DIR {quote(root)} ABSOLUTE)")
    out += [
        "",
        "if(NOT CMAKE_CXX_STANDARD)",
        f"  set(CMAKE_CXX_STANDARD {manifest.std})",
        "endif()",
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
        "set(CMAKE_CXX_EXTENSIONS OFF)",
        'set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/bin")',
        "",
    ]
    build = manifest.build
    if build.defines or build.flags:
        out += _values("add_compile_definitions", [], build.defines)
        out += _values("add_compile_options", [], build.flags)
        out.append("")
    for conditional in manifest.when:
        settings = conditional.build
        if settings.defines or settings.flags:
            out += _when(
                conditional.condition,
                lambda condition, s=settings: [
                    *_values("add_compile_definitions", [], s.defines, condition),
                    *_values("add_compile_options", [], s.flags, condition),
                ],
            )
            out.append("")
    out += _find_packages(manifest.dependencies, graph)

    # Static libraries that go into a shared one must be position-independent code.
    by_name = {found.component.name: found.component for found in libraries}
    inside_shared: set[str] = set()
    pending = [name for c in by_name.values() if c.shared for name in c.uses]
    while pending:
        name = pending.pop()
        if name in by_name and name not in inside_shared:
            inside_shared.add(name)
            pending += by_name[name].uses
    if shared is not None:
        # Others choose, for example with Conan's shared option.
        out.append(
            f'option(BUILD_SHARED_LIBS "Build shared libraries" {"ON" if shared else "OFF"})'
        )
    conditional_settings = {
        found.component.target: manifest.conditional(found.component)
        for found in (*libraries, *executables)
    }
    for found in libraries:
        component = found.component
        lib, settings = component.target, component.settings
        key = component.where if manifest.libraries else "lib"
        assert component.directory is not None
        include_dir = path(component.include or component.directory)
        if found.sources:
            if shared is not None:
                out += _call("add_library", [lib], map(path, found.sources))
            else:
                kind = "SHARED" if component.shared else "STATIC"
                out += _call("add_library", [lib, kind], map(path, found.sources))
            properties = ["OUTPUT_NAME", component.name]
            if component.shared or shared is not None:
                # Without exports, Visual C++ makes no import library to link against.
                properties += ["WINDOWS_EXPORT_ALL_SYMBOLS", "ON"]
            if component.name in inside_shared and not component.shared and shared is None:
                properties += ["POSITION_INDEPENDENT_CODE", "ON"]
            out += _call("set_target_properties", [lib, "PROPERTIES", *properties])
            out += _call("target_include_directories", [lib, "PUBLIC", include_dir])
            out += _call("target_include_directories", [lib, "PRIVATE", path(component.directory)])
            scope = "PUBLIC"
        else:
            if component.shared:
                raise CxyError(f"{key}.shared needs library sources to compile, but there are none")
            flagged = [
                f"{conditional.where}.{key}"
                for conditional, extra in conditional_settings[lib]
                if extra.flags
            ]
            if settings.flags or flagged:
                where = key if settings.flags else flagged[0]
                raise CxyError(
                    f"{where}.flags apply to library sources, but there are none; use build.flags"
                )
            out += _call("add_library", [lib, "INTERFACE"])
            out += _call("target_include_directories", [lib, "INTERFACE", include_dir])
            scope = "INTERFACE"
        out += _call("target_compile_features", [lib, scope, standard])
        out += _definitions(lib, scope, settings.defines)
        out += _options(lib, "PRIVATE", settings.flags)
        out += _conditional_settings(conditional_settings[lib], lib, scope, "PRIVATE")
        out += _link(lib, scope, links(component))
        out.append("")

    # Tests link the code of every component, apart from main files.
    objects: list[str] = []
    for found in executables:
        component = found.component
        exe, settings = component.target, component.settings
        src_dir = None if component.directory is None else path(component.directory)
        exe_links = links(component)
        if found.sources and src_dir is not None:
            # An object library lets the tests link the application's code without main().
            app = component.objects
            out += _call("add_library", [app, "OBJECT"], map(path, found.sources))
            out += _call("target_include_directories", [app, "PUBLIC", src_dir])
            out += _call("target_compile_features", [app, "PUBLIC", standard])
            # Tests that link the objects see the same definitions.
            out += _definitions(app, "PUBLIC", settings.defines)
            out += _options(app, "PRIVATE", settings.flags)
            out += _conditional_settings(conditional_settings[exe], app, "PUBLIC", "PRIVATE")
            out += _link(app, "PUBLIC", exe_links)
            exe_links = [app, *exe_links]
            objects.append(app)
        assert found.main is not None
        out += _call("add_executable", [exe], [path(found.main)])
        if src_dir is not None:
            out += _call("target_include_directories", [exe, "PRIVATE", src_dir])
        out += _call("target_compile_features", [exe, "PRIVATE", standard])
        if not found.sources:
            out += _definitions(exe, "PRIVATE", settings.defines)
        out += _options(exe, "PRIVATE", settings.flags)
        own = conditional_settings[exe]
        if found.sources:
            # The definitions come with the objects.
            own = [(c, Settings(flags=extra.flags)) for c, extra in own]
        out += _conditional_settings(own, exe, "PRIVATE", "PRIVATE")
        out += _link(exe, "PRIVATE", exe_links)
        out.append("")
    app_links = [*objects, *(list(library_targets.values()) or dependency_targets)]
    private_dirs = [
        path(found.component.directory)
        for found in sources.components
        if found.component.directory is not None
    ]
    search_dirs = list(map(path, manifest.include_directories))
    # Isolated tests compile the components' sources themselves, so they need their settings.
    # Only managed builds have them, whose manifest has no conditions left.
    assert not (isolated and manifest.when)
    built = [found.component.settings for found in (*libraries, *executables)]
    isolated_defines = list(dict.fromkeys(d for settings in built for d in settings.defines))
    isolated_flags = list(dict.fromkeys(f for settings in built for f in settings.flags))

    if programs:
        dev = {d.name: d for d in manifest.dev_dependencies}
        others = [d for d in dev.values() if d.name not in frameworks.ALL]

        # These must come first. Other libraries may have a main() too, such as some of Boost's,
        # and the linker uses the first that it finds. (CMake still puts the project's own
        # library before these, but that has no reason to have one.)
        def test_links(program: TestProgram) -> list[str]:
            framework = program.framework
            return [*framework.links(dev[framework.package], graph), *_targets(others, graph)]

        # CTest runs tests in the build directory by default.
        test_directory = []
        if manifest.test_working_directory is not None:
            base_dir = "CMAKE_CURRENT_SOURCE_DIR" if root is None else "ROOT_DIR"
            test_directory = [
                f'WORKING_DIRECTORY "${{{base_dir}}}/{quote(manifest.test_working_directory)[1:]}'
            ]

        modules = dict.fromkeys(program.framework.cmake_module for program in programs)
        body = _find_packages(dev.values(), graph)
        body += [f"include({module})" for module in modules]
        for program in programs:
            target = program.target
            body += ["", *_call("add_executable", [target], map(path, program.sources))]
            body += _call("target_include_directories", [target, "PRIVATE", *private_dirs])
            body += _call("target_compile_features", [target, "PRIVATE", standard])
            body += _link(target, "PRIVATE", [*test_links(program), *app_links])
            # Different programs may contain tests with the same name.
            body += _call(
                program.framework.discover_command,
                [],
                [
                    target,
                    "DISCOVERY_MODE PRE_TEST",
                    f'TEST_PREFIX "{target}:"',
                    *test_directory,
                ],
            )
        for program in programs:
            needed = (isolated or {}).get(program.sources[0]) if program.is_unit else None
            if needed is None:
                continue
            target = program.isolated_target
            files = [*program.sources, *needed]
            body += [
                "",
                *_call("add_executable", [target, "EXCLUDE_FROM_ALL"], map(path, files)),
            ]
            body += _call("target_include_directories", [target, "PRIVATE", *search_dirs])
            body += _call("target_compile_features", [target, "PRIVATE", standard])
            body += _definitions(target, "PRIVATE", isolated_defines)
            body += _options(target, "PRIVATE", isolated_flags)
            body += _link(target, "PRIVATE", [*test_links(program), *dependency_targets])
        out += ["if(BUILD_TESTING)", *(f"  {line}" if line else "" for line in body), "endif()"]
    return "\n".join(out).rstrip() + "\n"


def shared_default(sources: Sources) -> bool | None:
    """Whether the compiled libraries are shared by default, if they are all alike.

    Then the exported project lets others choose, with BUILD_SHARED_LIBS or Conan's shared
    option; otherwise, or without compiled libraries, None.
    """
    kinds = {found.component.shared for found in sources.libraries if found.sources}
    return next(iter(kinds)) if len(kinds) == 1 else None


def quote(value: str) -> str:
    """Quote a CMake argument, disabling variable expansion."""
    for char in ("\\", '"', "$"):
        value = value.replace(char, f"\\{char}")
    return f'"{value}"'


def _call(command: str, arguments: Iterable[str], items: Iterable[str] = ()) -> list[str]:
    head = f"{command}({' '.join(arguments)}"
    items = list(items)
    if not items:
        return [f"{head})"]
    return [head, *(f"  {item}" for item in items), ")"]


def _link(target: str, scope: str, libraries: Iterable[str]) -> list[str]:
    libraries = list(libraries)
    return _call("target_link_libraries", [target, scope, *libraries]) if libraries else []


def _definitions(
    target: str, scope: str, defines: Sequence[str], condition: Condition | None = None
) -> list[str]:
    return _values("target_compile_definitions", [target, scope], defines, condition)


def _options(
    target: str, scope: str, flags: Sequence[str], condition: Condition | None = None
) -> list[str]:
    return _values("target_compile_options", [target, scope], flags, condition)


def _values(
    command: str,
    arguments: Sequence[str],
    values: Sequence[str],
    condition: Condition | None = None,
) -> list[str]:
    """Call a command with values, as they are or only when a condition holds at build time."""
    if not values:
        return []
    if condition is None:
        return _call(command, arguments, map(quote, values))
    test = conditions.generator_expression(condition)
    return _call(command, arguments, (f'"$<{test}:{_in_expression(v)}>"' for v in values))


def _when(condition: Condition, body: _Body) -> list[str]:
    """Lines that apply only when a condition holds.

    An if() block is easier to read, but CMake can only tell the build type at build time,
    so conditions on it go in generator expressions.
    """
    if conditions.needs_generator_expression(condition):
        return body(condition)
    lines = body(None)
    if not lines:
        return []
    return [f"if({conditions.cmake_if(condition)})", *(f"  {line}" for line in lines), "endif()"]


def _conditional_settings(
    conditional: Sequence[tuple[Conditional, Settings]],
    target: str,
    definitions: str,
    options: str,
) -> list[str]:
    """A target's settings from [when] tables, with the scopes of its definitions and options."""
    out: list[str] = []
    for when, settings in conditional:
        out += _when(
            when.condition,
            lambda condition, s=settings: [
                *_definitions(target, definitions, s.defines, condition),
                *_options(target, options, s.flags, condition),
            ],
        )
    return out


_SPECIAL_IN_EXPRESSION = {">": "$<ANGLE-R>", ",": "$<COMMA>", ";": "$<SEMICOLON>"}


def _in_expression(value: str) -> str:
    """Quote a value for a generator expression inside a quoted argument."""
    text = quote(value)[1:-1]
    return re.sub("[>,;]", lambda match: _SPECIAL_IN_EXPRESSION[match.group()], text)


def _find_packages(dependencies: Iterable[Dependency], graph: Mapping[str, CMakeInfo]) -> list[str]:
    packages = dict.fromkeys(conan.resolve(d, graph).package for d in dependencies)
    return [f"find_package({package} REQUIRED CONFIG)" for package in packages]


def _targets(dependencies: Iterable[Dependency], graph: Mapping[str, CMakeInfo]) -> list[str]:
    targets: list[str] = []
    for dependency in dependencies:
        targets += dependency.cmake_targets or (conan.resolve(dependency, graph).target,)
    return targets
